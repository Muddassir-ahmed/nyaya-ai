from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.emergency_contact import EmergencyContact
from app.schemas.emergency import EmergencyContact as EmergencyContactSchema
from app.schemas.emergency import EmergencyType


class EmergencyService:
    @staticmethod
    def _to_schema(
        contact: EmergencyContact,
    ) -> EmergencyContactSchema:
        return EmergencyContactSchema.model_validate(
            contact,
            from_attributes=True,
        )

    @staticmethod
    async def _get_contacts_for_jurisdiction(
        db: AsyncSession,
        emergency_type: EmergencyType,
        jurisdiction: str,
    ) -> list[EmergencyContact]:
        """
        Retrieve verified and active contacts for one emergency type
        and one jurisdiction.
        """
        statement = (
            select(EmergencyContact)
            .where(
                EmergencyContact.emergency_type == emergency_type.value,
                EmergencyContact.jurisdiction == jurisdiction,
                EmergencyContact.is_verified.is_(True),
                EmergencyContact.is_active.is_(True),
            )
            .order_by(EmergencyContact.name)
        )

        result = await db.execute(statement)

        return list(result.scalars().all())

    @staticmethod
    async def get_verified_contacts(
        db: AsyncSession,
        emergency_type: EmergencyType,
        jurisdiction: str = "India",
    ) -> list[EmergencyContactSchema]:
        """
        Return verified and active emergency contacts using the hierarchy:

        1. Requested jurisdiction + emergency type
        2. India-wide + emergency type
        3. India-wide universal emergency number 112

        Emergency numbers are always retrieved from the verified database.
        They are never generated by the LLM.
        """

        # ---------------------------------------------------------
        # LEVEL 1
        # State / requested jurisdiction specific contact
        # ---------------------------------------------------------

        jurisdiction_contacts = (
            await EmergencyService._get_contacts_for_jurisdiction(
                db=db,
                emergency_type=emergency_type,
                jurisdiction=jurisdiction,
            )
        )

        if jurisdiction_contacts:
            return [
                EmergencyService._to_schema(contact)
                for contact in jurisdiction_contacts
            ]

        # ---------------------------------------------------------
        # LEVEL 2
        # India-wide contact for the same emergency type
        # ---------------------------------------------------------

        if jurisdiction != "India":
            india_contacts = (
                await EmergencyService._get_contacts_for_jurisdiction(
                    db=db,
                    emergency_type=emergency_type,
                    jurisdiction="India",
                )
            )

            if india_contacts:
                return [
                    EmergencyService._to_schema(contact)
                    for contact in india_contacts
                ]

        # ---------------------------------------------------------
        # LEVEL 3
        # Universal India emergency fallback: 112
        # ---------------------------------------------------------

        fallback_statement = (
            select(EmergencyContact)
            .where(
                EmergencyContact.emergency_type
                == EmergencyType.OTHER.value,
                EmergencyContact.phone_number == "112",
                EmergencyContact.jurisdiction == "India",
                EmergencyContact.is_verified.is_(True),
                EmergencyContact.is_active.is_(True),
            )
            .limit(1)
        )

        fallback_result = await db.execute(fallback_statement)

        fallback_contact = fallback_result.scalar_one_or_none()

        if fallback_contact is None:
            return []

        return [
            EmergencyService._to_schema(fallback_contact)
        ]