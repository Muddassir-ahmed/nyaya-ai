from sqlalchemy.ext.asyncio import AsyncSession

from app.schemas.emergency import EmergencyResponse, EmergencyType
from app.services.emergency_service import EmergencyService
from app.services.query_analyzer import QueryAnalyzer
from app.core.text_matching import contains_any


class EmergencyOrchestrator:
    """
    Coordinates emergency detection, emergency-type classification,
    verified contact retrieval, and immediate safety guidance.

    Important:
    - Emergency numbers are NEVER generated by an LLM.
    - Contacts always come from EmergencyService.
    - Emergency guidance is deterministic in this first version.
    """

    def __init__(
        self,
        query_analyzer: QueryAnalyzer | None = None,
    ):
        self.query_analyzer = query_analyzer or QueryAnalyzer()

    @staticmethod
    def _normalize_jurisdiction(
        jurisdiction: str | None,
    ) -> str | None:
        """
        Normalize supported jurisdiction names/codes to the values used
        by the emergency directory.

        This prevents values such as "AS" and "Assam" from being treated
        as different jurisdictions during emergency contact retrieval.
        """

        if jurisdiction is None:
            return None

        value = jurisdiction.strip()

        if not value:
            return None

        aliases = {
            "IN": "India",
            "INDIA": "India",
            "AS": "Assam",
            "ASSAM": "Assam",
            "MH": "Maharashtra",
            "MAHARASHTRA": "Maharashtra",
            "KA": "Karnataka",
            "KARNATAKA": "Karnataka",
        }

        return aliases.get(value.upper(), value)

    @classmethod
    def _resolve_jurisdiction(
        cls,
        explicit_jurisdiction: str | None,
        detected_jurisdiction: str | None,
    ) -> str:
        """
        Resolve which jurisdiction should be used for emergency lookup.

        Priority:
        1. Explicit jurisdiction supplied by the caller.
        2. Jurisdiction detected from the user's query.
        3. India as the safe national default.
        """

        explicit = cls._normalize_jurisdiction(
            explicit_jurisdiction
        )

        if explicit is not None:
            return explicit

        detected = cls._normalize_jurisdiction(
            detected_jurisdiction
        )

        if detected is not None:
            return detected

        return "India"

    @staticmethod
    def _detect_emergency_type(
        query: str,
    ) -> EmergencyType:
        """
        Determine the most likely emergency category from the user's query.

        Matching is deterministic and boundary-aware to reduce
        false classifications such as:

        - "fire" matching "firewall"
        - "hack" matching "hackathon"
        - "child" matching "childhood"

        Emergency contact numbers are never decided or generated here.
        """

        text = query.lower().strip()

        cyber_keywords = {
            "cybercrime",
            "cyber",
            "hacked",
            "hack",
            "phishing",
            "online fraud",
            "otp",
            "account hacked",
            "instagram hacked",
            "email hacked",
        }

        if contains_any(text, cyber_keywords):
            return EmergencyType.CYBERCRIME

        child_keywords = {
            "child",
            "kid",
            "kidnapped child",
            "missing child",
            "child kidnapped",
            "child abuse",
        }

        if contains_any(text, child_keywords):
            return EmergencyType.CHILD_SAFETY

        women_keywords = {
            "woman",
            "women",
            "girl",
            "sexual assault",
            "domestic violence",
            "domestic abuse",
            "molestation",
        }

        if contains_any(text, women_keywords):
            return EmergencyType.WOMEN_SAFETY

        fire_keywords = {
            "fire",
            "burning",
            "building on fire",
            "house on fire",
            "smoke",
        }

        if contains_any(text, fire_keywords):
            return EmergencyType.FIRE

        medical_keywords = {
            "bleeding",
            "unconscious",
            "dying",
            "heart attack",
            "stroke",
            "not breathing",
            "breathing difficulty",
            "severe injury",
            "injured",
        }

        if contains_any(text, medical_keywords):
            return EmergencyType.MEDICAL

        disaster_keywords = {
            "flood",
            "earthquake",
            "cyclone",
            "landslide",
            "disaster",
            "building collapsed",
        }

        if contains_any(text, disaster_keywords):
            return EmergencyType.DISASTER

        police_keywords = {
            "being attacked",
            "attacking me",
            "someone attacking",
            "someone is attacking",
            "threatening to kill",
            "threatened to kill",
            "trying to kill",
            "hostage",
            "kidnapped",
            "robbery",
            "murder",
        }

        if contains_any(text, police_keywords):
            return EmergencyType.POLICE

        return EmergencyType.OTHER

    @staticmethod
    def _build_immediate_actions(
        emergency_type: EmergencyType,
    ) -> list[str]:
        """
        Return concise immediate safety guidance.

        These instructions are deliberately conservative and do not
        contain emergency phone numbers.
        """

        common_actions = [
            "If you are in immediate danger, move to a safer location if you can do so safely.",
        ]

        type_specific_actions = {
            EmergencyType.POLICE: [
                "Avoid confrontation and prioritize getting yourself to a safe place.",
                "Preserve relevant evidence if doing so does not put you at greater risk.",
            ],
            EmergencyType.FIRE: [
                "Leave the affected building or area immediately if it is safe to do so.",
                "Do not re-enter a burning or unsafe building.",
            ],
            EmergencyType.MEDICAL: [
                "Seek immediate medical assistance.",
                "If the person is unconscious or seriously injured, avoid unnecessary movement unless there is an immediate danger.",
            ],
            EmergencyType.WOMEN_SAFETY: [
                "Move to a safe place and avoid confronting the person threatening you.",
                "If possible, contact someone you trust and let them know where you are.",
            ],
            EmergencyType.CHILD_SAFETY: [
                "Prioritize getting the child to a safe place if this can be done safely.",
                "Preserve identifying information, messages, photographs, or other relevant evidence.",
            ],
            EmergencyType.DISASTER: [
                "Follow instructions from local emergency authorities.",
                "Move away from unstable structures and other immediate hazards.",
            ],
            EmergencyType.CYBERCRIME: [
                "If your account or device is compromised, secure it from a safe device if possible.",
                "Do not share OTPs, passwords, recovery codes, or other authentication credentials with anyone.",
                "Preserve relevant messages, transaction records, screenshots, and other digital evidence.",
            ],
            EmergencyType.OTHER: [
                "Prioritize your immediate physical safety.",
                "Contact an appropriate emergency authority as soon as you can do so safely.",
            ],
        }

        return common_actions + type_specific_actions[emergency_type]

    async def handle(
        self,
        db: AsyncSession,
        query: str,
        jurisdiction: str | None = None,
    ) -> EmergencyResponse:
        """
        Analyze a user query and produce a safety-aware emergency response.

        Non-emergency queries return an empty emergency response.
        """

        analysis = self.query_analyzer.analyze(query)

        if not (
            analysis.intent.value == "emergency"
            or analysis.urgency.value == "emergency"
        ):
            return EmergencyResponse(
                is_emergency=False,
                emergency_type=None,
                immediate_actions=[],
                contacts=[],
                safety_warning=None,
                verification_note=None,
            )

        emergency_type = self._detect_emergency_type(
            analysis.original_query
        )
        resolved_jurisdiction = self._resolve_jurisdiction(
            explicit_jurisdiction=jurisdiction,
            detected_jurisdiction=analysis.jurisdiction,
        )

        # Emergency contact retrieval is strictly delegated to the
        # verified EmergencyService.
        contacts = await EmergencyService.get_verified_contacts(
            db=db,
            emergency_type=emergency_type,
            jurisdiction=resolved_jurisdiction,
        )

        return EmergencyResponse(
            is_emergency=True,
            emergency_type=emergency_type,
            immediate_actions=self._build_immediate_actions(
                emergency_type
            ),
            contacts=contacts,
            safety_warning=(
                "If you are in immediate danger, prioritize your safety "
                "and follow instructions from emergency authorities. "
                "Do not rely on this system as a replacement for "
                "emergency services or qualified professionals."
            ),
            verification_note=(
                "Emergency contact information is retrieved only from "
                "verified, active records in the NyayaAI emergency directory. "
                "Emergency numbers are not generated by the language model."
            ),
        )


def get_emergency_orchestrator() -> EmergencyOrchestrator:
    return EmergencyOrchestrator()
